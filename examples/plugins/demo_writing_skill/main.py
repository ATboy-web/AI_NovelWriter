"""示例插件：一个最小的写作技能包。

## 这个示例存在的意义

`~/.ai_novel_writer/plugins/` 在全新安装时是**空的**。
空目录意味着用户点开「插件中心」看到的是"尚未安装任何插件"——
"插件功能已启用"这件事**无法被验证**。

本示例提供一个**开箱可验证**的对象：装它、启用它，
面板底部的"已生效：N 个写作技能包注入写作提示词"会从 0 变成 1。
这就是「装上了」与「生效了」的区别。

## 它做什么

1. `get_writing_skills()` —— 唯一的必需接口，返回技能包列表。
   - `prompt`：拼进写作上下文，指导 AI 怎么写；
   - `rules`：进入 `AntiSlopProcessor` 的额外禁用表，
     AI 写出的正文里出现这些词会被判为"AI 味"。

2. 就这些。**不需要**继承任何基类、**不需要**导入本应用的模块 ——
   插件就是一个普通 Python 文件，靠导出约定好的函数名来声明能力。

## 怎么装

「插件中心」→「安装插件」→ 输入 `dir` → 选中本目录
（`examples/plugins/demo_writing_skill/`）。
装完在左侧列表选中它 → 点「启用」→ 看底部统计。
"""

__all__ = ["get_writing_skills", "get_library"]


def get_writing_skills():
    """返回本插件提供的写作技能包。"""
    return [
        {
            "name": "去油文风",
            "prompt": (
                "行文克制：多用具体动作与感官细节，少用概括性抒情；"
                "每段至少推进一处情节或揭示一处信息，避免空转。"
            ),
            "rules": [
                "总而言之",
                "不禁感叹",
            ],
        }
    ]


def get_library():
    """顺带演示"一个插件可同时提供多种能力"（库扩充）。"""
    return {
        "type": "elements",
        "category": "示例分类",
        "items": [
            {"name": "示例元素", "template": "一个被反复擦拭的旧物件，每次出现都少一层漆"},
        ],
    }
