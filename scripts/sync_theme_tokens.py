# -*- coding: utf-8 -*-
"""从 app/theme_system.py 生成移动端 ThemeTokens.kt（单一来源的跨端同步）。

用法：python scripts/sync_theme_tokens.py
产物：mobile-app/novel-app/app/src/main/java/com/ainovelwriter/ui/theme/ThemeTokens.kt

纪律（与项目"同一事实一处派生"一致）：
- 主题取值的唯一权威是 app/theme_system.py；Kotlin 侧**只放生成物**，
  文件头标注 DO NOT EDIT；
- tests/test_theme_system.py 逐值比对生成物与 Python 权威，漂移即红；
- 本脚本幂等：重复运行产物逐字节一致。
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
sys.path.insert(0, str(REPO / "scripts"))

from _console_utf8 import make_stdout_utf8_safe  # noqa: E402

make_stdout_utf8_safe()

from app import theme_system as ts  # noqa: E402

TARGET = (
    REPO
    / "mobile-app"
    / "novel-app"
    / "app"
    / "src"
    / "main"
    / "java"
    / "com"
    / "ainovelwriter"
    / "ui"
    / "theme"
    / "ThemeTokens.kt"
)


def argb(hex_color: str) -> str:
    return "0xFF" + hex_color.lstrip("#").upper() + "L"


def kotlin_map(entries: list[tuple[str, str]]) -> str:
    return "mapOf(\n" + "".join(f'        "{k}" to {v},\n' for k, v in entries) + "    )"


def build() -> str:
    lines = [
        "// AUTO-GENERATED by scripts/sync_theme_tokens.py — DO NOT EDIT.",
        "// 唯一权威：app/theme_system.py（桌面/移动共用同一套主题令牌）。",
        "// 漂移守卫：tests/test_theme_system.py::TestCrossPlatformSync",
        "package com.ainovelwriter.ui.theme",
        "",
        "object ThemeTokens {",
        f"    val THEME_IDS = listOf({', '.join(chr(34) + t + chr(34) for t in ts.THEME_IDS)})",
        f'    const val DEFAULT_THEME = "{ts.DEFAULT_THEME}"',
        "",
        "    val THEME_NAMES = " + kotlin_map([(t, f'"{ts.THEME_META[t]["name_cn"]}"') for t in ts.THEME_IDS]),
        "",
        "    val THEME_DESCRIPTIONS = "
        + kotlin_map([(t, f'"{ts.THEME_META[t]["description"]}"') for t in ts.THEME_IDS]),
        "",
        "    // 每主题的颜色令牌（ARGB）。键名与 Theme.kt 的状态驱动令牌一一对应。",
        "    val COLORS: Map<String, Map<String, Long>> = mapOf(",
    ]
    for tid in ts.THEME_IDS:
        pal = ts.THEMES[tid]
        entries = [(name, argb(pal[key])) for name, key in ts.MOBILE_TOKEN_MAP.items()]
        lines.append(f'        "{tid}" to ' + kotlin_map(entries).replace("\n", "\n    ") + ",")
    lines.append("    )")
    lines.append("")
    lines.append("    // 统一间距刻度（dp，与桌面 px 同值 —— 4px 基准栅格）")
    lines.append("    val SPACING = " + kotlin_map([(k, str(v)) for k, v in ts.SPACING_SCALE.items()]))
    lines.append("")
    lines.append("    // 统一字体层级（sp；角色名与桌面 FONT_ROLES 对应）")
    lines.append(
        "    val TYPE_SCALE = " + kotlin_map([(role, str(v["mobile_sp"])) for role, v in ts.TYPE_SCALE.items()])
    )
    lines.append("}")
    return "\n".join(lines) + "\n"


def main() -> None:
    content = build()
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    if TARGET.exists() and TARGET.read_text(encoding="utf-8") == content:
        print("ThemeTokens.kt 已是最新（幂等，无写入）")
        return
    TARGET.write_text(content, encoding="utf-8", newline="\n")
    print(f"已生成 {TARGET.relative_to(REPO)}（{len(content)} 字符）")


if __name__ == "__main__":
    main()
